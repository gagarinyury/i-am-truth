#!/usr/bin/env python3
"""
Верификатор чисел — реализация решения D-14.

Ни одно число не попадает в отчёт без обратной сверки с первоисточником, кем бы оно ни
было извлечено: структурным парсером, PDF-конвертером или мультимодальной моделью.

Основание — три независимых сигнала за 27.08.2026 (F-27, F-29, prior-art п.4):
любой источник уверенно врёт именно на плотных числах.

  python3 eval/verify_numbers.py --claims claims.json --source статья.xml
"""
import argparse
import collections
import json
import math
import os
import re
import sys
import unicodedata

CONTEXT_BEFORE = 260   # заголовок метки бывает далеко до числа
CONTEXT_AFTER = 120

# Списка «тривиальных чисел» здесь больше нет. Он был вкусовым: `{"0","1","2","5",
# "10","100","95"}` — семь значений, выбранных на глаз, при этом «3» и «96»
# считались данными статьи, а «95» не считалось никогда, даже когда это была доля
# в процентах. Хуже того, пропущенные числа попадали в знаменатель сводки, и
# отчёт объявлял найденными 566 чисел из 566, тогда как искали 474.
# Теперь их обнуляет вес улики: число, которое нашлось бы в этом документе само
# собой, весит ноль бит по измерению, а не по нашему решению.


def normalise(text: str) -> str:
    """Приводит текст к виду, в котором числа сравнимы.

    Единый минус, неразрывные и тонкие пробелы, разделители разрядов.
    Разметка (JATS/HTML) снимается: иначе теги встают между числом и его меткой и
    проверка метки даёт лавину ложных срабатываний — поймано 27.08 на PMC13311639,
    282 ложных из 342.

    Тег обязан начинаться с буквы (или «/»): в научном тексте «<» и «>» — это ещё
    и знаки сравнения, «p < 0.001 … reliability coefficients > 0.8». Паттерн
    `<[^>]+>` считал всё между ними тегом и вырезал вместе с числами: на одной
    статье в PDF так терялась треть текста, 24 488 символов из 72 468, и честно
    процитированные числа получали статус UNVERIFIED (F-41).
    """
    t = unicodedata.normalize("NFKC", text)
    if "<" in t and ">" in t:
        t = re.sub(r"</?[A-Za-z][^<>]*>", " ", t)
    t = t.replace("−", "-").replace("–", "-").replace("—", "-")
    t = re.sub(r"[    ]", " ", t)
    return t


def number_variants(num: str) -> list:
    """Все написания одного числа, встречающиеся в статьях.

    1234.5 -> {1234.5, 1,234.5, 1 234.5, 1234,5}
    """
    num = num.strip()
    neg = num.startswith("-")
    core = num.lstrip("-")
    if "." in core:
        whole, frac = core.split(".", 1)
    else:
        whole, frac = core, None

    groups = []
    if len(whole) > 3:
        rev = whole[::-1]
        groups = [",".join(rev[i:i + 3] for i in range(0, len(rev), 3))[::-1],
                  " ".join(rev[i:i + 3] for i in range(0, len(rev), 3))[::-1]]
    wholes = [whole] + groups

    out = set()
    for w in wholes:
        out.add(w if frac is None else f"{w}.{frac}")
        if frac is not None:
            out.add(f"{w},{frac}")          # десятичная запятая
    return sorted(("-" if neg else "") + v for v in out)


# --------------------------------------------------------------- вес улики
#
# Зачем это вообще. «Число найдено в статье» — сигнал слабый, и слабеет он тем
# сильнее, чем лучше сработала добыча: замер 29.08 на разборе
# `10.1136/jitc-2025-014726` (341 тыс. знаков после `normalise`) показал, что
# ВЫДУМАННОЕ число вида `x.y` находится в этом документе в 33% случаев, а целое из
# двух-трёх цифр — в 46%. Значит «0 не найдено из 474» на полном тексте — исход,
# ожидаемый и для чисел, которых модель никогда не видела. На абстракте (1.7 тыс.
# знаков) та же доля 1%. Отсюда неприятный вывод, который стоит держать в голове:
# **чем полнее retrieval, тем меньше значит сам факт нахождения** — а retrieval и
# есть главный тезис проекта.
#
# Поэтому считается не факт, а его информативность. Нулевое распределение берётся
# из самого документа — без сэмплинга, без подбора порогов, одним проходом. Для
# формы числа S (столько-то цифр до точки, столько-то после):
#
#       p(случайно) = |различных значений формы S, встречающихся в документе|
#                     ───────────────────────────────────────────────────────
#                                     |мощность формы S|
#
#       вес улики = −log2 p, в битах
#
# «2» в статье, где встречаются все однозначные числа, весит 0 бит — и списка
# тривиальных чисел для этого больше не нужно, их обнуляет измерение, а не наш
# вкус. «15,264» весит около 12 бит: столько же, сколько стоит угадать его.
#
# ⚠️ Что именно измеряет эта величина и против чего она НЕ защищает.
#
# Числитель здесь измерен точно: это занятые значения самого документа, посчитанные
# проходом по нему. Допущение сидит в знаменателе — мощность формы берётся так,
# будто внутри формы все значения равновероятны. Отсюда `p` — вероятность совпасть
# для числа, выбранного из формы **равномерно случайно**, и калибровка 29.08 ставила
# ровно такой опыт: подставлялись случайные числа, доли сошлись (33% против 33%,
# 1% против 1%).
#
# Здесь до 31.08 стояло, что допущение **занижает** вес и потому безопасно. Это
# неверно, и направление важнее самой поправки. Модель не выдумывает числа
# равномерно: она пишет правдоподобные — круглые, малые проценты, значения, похожие
# на соседние в той же таблице, — то есть тяготеет ровно к тем клеткам формы,
# которые документ уже занял. Для такого источника вероятность случайного совпадения
# **выше** расчётной, а значит шесть бит скорее переоценивают улику, чем недооценивают.
#
# Поэтому граница читается так: вес улики отделяет число, взятое из этой статьи, от
# числа, попавшегося по совпадению — и не отделяет его от правдоподобной
# галлюцинации. Второе потребовало бы замера на выдумках самой модели, а не на
# случайных подстановках, и такого замера у проекта нет.
_NUM_IN_TEXT = re.compile(r"(?<![\d.,])(\d+)(?:\.(\d+))?(?![\d])")

# Порог «сильной» улики. Не назначен, а взят из того же замера: формы, которые
# при подстановке выдуманных чисел находились в 1-2% случаев (`x.yy`, целые из
# четырёх цифр), дают около 6 бит; формы, находившиеся в 33-46% (`x.y`, целые из
# двух-трёх цифр), — около 1-1.6 бита. Шесть бит и есть та граница, где кончается
# то, что нашлось бы само.
STRONG_BITS = 6.0


def shape_of(num: str) -> tuple:
    """Форма числа: сколько цифр до точки и сколько после."""
    core = str(num).strip().lstrip("-")
    whole, _, frac = core.partition(".")
    return (len(whole), len(frac))


def shape_space(shape: tuple) -> int:
    """Сколько разных чисел этой формы существует вообще."""
    i, d = shape
    if i <= 0:
        return 1
    whole = 10 if i == 1 else 9 * 10 ** (i - 1)
    return whole * 10 ** d


def document_shapes(source: str) -> dict:
    """Форма → множество различных значений этой формы, занятых документом."""
    out = collections.defaultdict(set)
    for m in _NUM_IN_TEXT.finditer(source):
        whole, frac = m.group(1), m.group(2) or ""
        out[(len(whole), len(frac))].add(f"{whole}.{frac}" if frac else whole)
    return out


def chance_rate(num: str, shapes: dict) -> float:
    """Вероятность, что число этой формы нашлось бы в документе само собой.

    Доля может выйти больше единицы: мощность формы считается без ведущих нулей
    (двузначных чисел 90, от 10 до 99), а документ их содержит — «07» из дат.
    Тогда берётся единица, то есть нулевой вес. Так честнее, чем расширять
    пространство: сверка калибровалась на форме без ведущих нулей и на ней сошлась.

    Калибровка 29.08 на `10.1136/jitc-2025-014726`: модель против подстановки
    выдуманных чисел — 33% против 33% (`x.y`), 42% против 46% (целые 2-3 знака),
    1% против 1% (`x.yy`), 2% против 2% (целые 4 знака).
    """
    sh = shape_of(num)
    occupied = max(1, len(shapes.get(sh) or ()))
    return min(1.0, occupied / shape_space(sh))


def evidence_bits(num: str, shapes: dict) -> float:
    """Вес улики в битах. 0 означает «нашлось бы и без всякой статьи»."""
    p = chance_rate(num, shapes)
    return 0.0 if p >= 1.0 else round(-math.log2(p), 1)


# Сколько вхождений одного числа осматривать. Числа вроде «2.1» встречаются в
# статье десятками раз; проверять все — дорого и бессмысленно, но проверять одно
# первое — неверно (замер 29.08: 76% найденных чисел встречаются больше одного
# раза, медиана 2, максимум 118, F-63).
MAX_OCCURRENCES = 40

# ------------------------------------------------------------------ знак числа
#
# Шаблон числа, общий для всех слоёв. До 31.08 он был выписан отдельно в
# `pipeline`, `grounding` и `cells` тремя одинаковыми строками — и все три
# начинались с `\d`, то есть **знака не видели вовсе**. Замер прямой:
#
#     verify([{"value": "0.69", "label": "absolute risk difference"}],
#            "The absolute risk difference was -0.69 percentage points")
#     → VERIFIED
#
# То есть разность рисков, записанная с противоположным знаком, подтверждалась
# первоисточником. Это тот же класс, ради которого написана `check_group`, —
# инверсия направления (F-12), — только пропущенный на уровень ниже: там ловилась
# подмена группы, здесь беспрепятственно проходила подмена знака.
#
# Минус берётся в число только тогда, когда он **знак**, а не дефис диапазона.
# Различает их предшествующий символ: в «1.05-1.42» перед дефисом стоит цифра, и
# запрет `(?<![\d.,])` не даёт прочитать его как минус — верхняя граница
# доверительного интервала остаётся положительной. В «was -0.69» перед минусом
# пробел, и он читается как знак. Иначе цена была бы обратной и хуже: каждая
# вторая граница ДИ в статье получала бы ложное «не найдено», а ложное обвинение
# дороже пропуска — это правило проекта.
NUM_PATTERN = (r"(?<![\d.,])-?(?:\d{1,3}(?:[\u00a0\u202f ,]\d{3})+(?:\.\d+)?"
               r"|\d+(?:\.\d+)?|\.\d+)")
NUM = re.compile(NUM_PATTERN)

# Разделители разрядов, которые снимаются при сравнении значений. Список общий для
# всех слоёв: до 31.08 каждый снимал свой набор, и «15 264» с тонким пробелом из
# таблицы не сходилось с «15264» из разбора — число считалось разным в индексе
# ячеек и в сводке.
GROUP_SEPARATORS = (",", " ", "\u00a0", "\u202f")


def norm_value(raw) -> str:
    """Значение без разделителей разрядов. Знак остаётся: он часть числа."""
    out = str(raw)
    for sep in GROUP_SEPARATORS:
        out = out.replace(sep, "")
    return out


def find_occurrences(num: str, source: str, limit: int = MAX_OCCURRENCES) -> list:
    """Вхождения числа С ТЕМ ЖЕ ЗНАКОМ, что заявлен. Совместимая обёртка."""
    same, _ = find_occurrences_signed(num, source, limit)
    return same


def find_occurrences_signed(num: str, source: str,
                            limit: int = MAX_OCCURRENCES) -> tuple:
    """`(вхождения с тем же знаком, вхождения с противоположным)`.

    Раньше возвращалось первое вхождение, и на нём же строились проверка метки и
    проверка группы. Это значит, что число сверялось с произвольным местом
    документа: если «19.7» стоит в статье шесть раз, метка проверялась у первого,
    а принадлежало число, возможно, шестому. Отсюда шли и ложные `label mismatch`,
    и невозможность поймать настоящую инверсию.

    Второй список — не диагностика, а вердикт: если число нашлось только с другим
    знаком, «нашлось» о нём сказать нельзя. Возвращается отдельно, чтобы отчёт мог
    назвать разницу словами вместо тихого UNVERIFIED — «числа нет в статье» и «в
    статье оно с обратным знаком» это разные сведения, и второе сильнее.
    """
    num = str(num).strip()
    want_neg = num.startswith("-")
    core = num.lstrip("-")
    same, opposite = [], []
    for v in number_variants(core):
        # границы: число не должно быть частью более длинного числа
        # Хвостовой запрет включает «точка и цифра»: без него «247» находилось
        # внутри «247.83» и число-претендент подтверждалось чужой дробью. На
        # мере веса улики это сказывается прямо — завышает долю найденного.
        pat = re.compile(r"(?<![\d.,])(-?)" + re.escape(v) + r"(?![\d]|\.\d)")
        for m in pat.finditer(source):
            # окно широкое: заголовок строки таблицы или подраздела может стоять
            # заметно раньше самого числа (поймано на реальном файле 27.08)
            st = max(0, m.start() - CONTEXT_BEFORE)
            hit = {"as": ("-" if m.group(1) else "") + v, "start": m.start(),
                   "negative": bool(m.group(1)),
                   "context": " ".join(source[st:m.end() + CONTEXT_AFTER].split())}
            (same if bool(m.group(1)) == want_neg else opposite).append(hit)
            if len(same) >= limit:
                return same, opposite
        if same or opposite:
            # написание найдено — другие варианты того же числа не нужны
            break
    return same, opposite


# Здесь стояла `find_number` — «первое вхождение», с подписью «оставлено для
# совместимости с зондами в `eval/`». Ни один зонд её не звал: оправдание было
# правдоподобным и непроверяемым, а функция мёртвой. Смотреть на первое
# вхождение вдобавок неверно по существу — 76% найденных чисел встречаются в
# статье больше одного раза (F-63), и `find_occurrences` заменила её именно
# поэтому. История правки записана в docs/02-verified-facts.md.


# Группы сравнения и их написания. Настраивается под предметную область.
# Маркеры групп сравнения — регулярные выражения, а не подстроки.
#
# Подстрока «control» ловила «glycemic control», «blood pressure control», «disease
# control» и объявляла числа принадлежащими контрольной группе. Отсюда шли все
# ложные инверсии, какие удалось поднять: 13 случаев на трёх прогонах Cheng, и во
# всех тринадцати метка содержала «glycemic control», а в контексте не было ни
# одного упоминания контрольной группы вообще (замер 29.08, F-56). Записанное в
# F-51 объяснение про три группы оказалось неверным — механизм другой.
#
# Отсюда правило: слово «control» считается названием группы, только если рядом
# стоит слово, обозначающее руку исследования, либо оно употреблено во
# множественном числе («matched controls»). Это не подобранный порог, а свойство
# языка: одиночное «control» в медицинском тексте почти всегда про контроль
# показателя, а не про группу.
ARM = r"(?:group|arm|cohort|patients|subjects|participants|users)"
DEFAULT_GROUPS = {
    "exposed": [rf"\bexposed\b", rf"\bexposure\s+{ARM}\b",
                rf"\btreated\s+{ARM}\b", rf"\bintervention\s+{ARM}\b",
                r"\bэкспон"],
    "control": [rf"\bcontrol\s+{ARM}\b", r"\bcontrols\b", r"\bcomparator\b",
                rf"\bcomparison\s+{ARM}\b", rf"\bunexposed\b",
                r"\bконтрольн", r"\bгруппа\s+сравнени"],
}

# --------------------------------------------------- предметные маркеры
#
# Это словарь ОДНОЙ предметной области — класса статей, на котором проект
# калибровался. Раньше `\bglp[-\s]?1\b` стоял в общем списке наравне со словом
# «exposed», то есть название класса препаратов было вшито в продукт, объявленный
# для биомедицины вообще.
#
# Замер 31.08 показал, сколько это на самом деле значит, и результат неприятный:
# **на этих словах держится почти всё покрытие проверки групп**. Убрать их —
# вердикт выносится для 4 чисел из 457 вместо 81 (McDonald) и для 0 из 474 вместо
# 60 (Cheng). То есть строка «0 инверсий» на обоих эталонах обеспечена не общим
# механизмом, а тем, что обе статьи про GLP-1.
#
# Поэтому слова остаются — выбрасывать работающее покрытие ради чистоты нельзя, —
# но лежат отдельно, названы тем, что они есть, и заменяются файлом без правки
# кода. Для другой области задайте свой набор через `TRUTH_GROUP_MARKERS`.
DOMAIN_MARKERS = {
    "exposed": [r"\bglp[-\s]?1\b", r"\bгруппа\s+glp"],
    "control": [],
}

for _g, _al in DOMAIN_MARKERS.items():
    DEFAULT_GROUPS.setdefault(_g, []).extend(_al)

#
# Файл задаётся `TRUTH_GROUP_MARKERS` и имеет вид `{"exposed": [...],
# "control": [...]}` — регулярные выражения, дополняющие список выше, а не
# заменяющие его. Отсутствие файла — норма, а не отказ.
def _extra_markers() -> dict:
    path = os.environ.get("TRUTH_GROUP_MARKERS", "").strip()
    if not path:
        return {}
    try:
        data = json.loads(open(path, encoding="utf-8").read())
    except Exception:                                            # noqa: BLE001
        # Молча продолжать нельзя: человек задал файл и вправе знать, что его не
        # прочитали. Но и падать из-за настройки, без которой продукт работает,
        # тоже неверно.
        print(f"⚠️  TRUTH_GROUP_MARKERS: не прочитан {path}", file=sys.stderr)
        return {}
    return {g: [str(x) for x in (data.get(g) or [])] for g in ("exposed", "control")}


for _g, _al in _extra_markers().items():
    DEFAULT_GROUPS.setdefault(_g, []).extend(_al)


# --------------------------------------------- имена рук из самого документа
#
# Зачем. Маркеры выше — это словарь, а руки исследования называются в каждой
# статье своими словами: «Vaccinated / Unvaccinated», «GLP-1 / Non-GLP-1»,
# «Users / Non-users». Отсюда покрытие проверки: на живых разборах вердикт
# выносился для 81 числа из 457 и 60 из 474, то есть «ноль инверсий» относилось к
# пятой части чисел.
#
# Правило, по которому имя принимается, одно и оно не догадывается ни о чём:
# **заголовок считается названием руки, только если в той же таблице есть его
# отрицание** — «Unvaccinated» рядом с «Vaccinated», «Non-users» рядом с «Users».
# Пара «слово и его отрицание» — это и есть объявление двух рук, сделанное самим
# документом; отрицание идёт в контроль, основа — в экспозицию.
#
# Проверка «основа тоже стоит колонкой» здесь несущая. Без неё префикс `un`
# срезался бы у чего угодно («under 65» → «der 65»), и продукт начал бы выносить
# обвинения в инверсии на основании опечатки в регулярном выражении. С ней
# ложное срабатывание требует, чтобы в одной таблице стояли две колонки, одна из
# которых буквально является отрицанием другой и при этом руками не является.
_NEGATION = re.compile(r"^(?:non[-\s]?|un|no[-\s]+)(.{3,})$", re.I)
# Хвосты, которыми заголовок обрастает в вёрстке: «(n = 15 264)», «, %», сноски.
_HEAD_TAIL = re.compile(r"\s*(?:\(.*?\)|\[.*?\]|,.*|[*†‡§¶].*)\s*$")


def _clean_header(raw: str) -> str:
    """Заголовок колонки без хвостов вёрстки. Составной берётся по последнему
    уровню: в «Before matching · Vaccinated» руку называет именно он."""
    h = str(raw or "").split("·")[-1].strip()
    h = _HEAD_TAIL.sub("", h).strip().lower()
    return h if 1 < len(h) <= 40 else ""


def markers_from_tables(tables: list) -> dict:
    """Дополнительные маркеры групп, взятые из заголовков колонок документа.

    Возвращает `{"exposed": [...], "control": [...]}` — регулярные выражения,
    которые вызывающий добавляет к словарю. Пустой ответ — обычный исход и не
    ошибка: если документ не назвал руки парой «слово и его отрицание», угадывать
    их не из чего, и молчание здесь правильнее догадки.
    """
    exposed, control = set(), set()
    for t in tables or []:
        cols = [_clean_header(c) for c in (t.get("columns") or [])]
        if not cols and t.get("rows"):
            cols = [_clean_header(c) for c in t["rows"][0]]
        present = {c for c in cols if c}
        for c in present:
            m = _NEGATION.match(c)
            if not m:
                continue
            base = m.group(1).strip()
            if base in present:
                control.add(c)
                exposed.add(base)
    def _pat(name):
        return r"\b" + re.escape(name) + r"\b"
    return {"exposed": sorted(_pat(x) for x in exposed),
            "control": sorted(_pat(x) for x in control)}


def groups_with(extra: dict) -> dict:
    """Словарь маркеров плюс имена, взятые из документа. Копия, не мутация:
    `DEFAULT_GROUPS` общий на процесс, а таблицы у каждой статьи свои — дописывать
    в общий словарь значило бы переносить руки одной статьи на разбор другой,
    ровно тот класс подмены, который продукт ищет у чужих работ."""
    if not extra or not (extra.get("exposed") or extra.get("control")):
        return DEFAULT_GROUPS
    return {g: list(DEFAULT_GROUPS.get(g, [])) + list(extra.get(g) or [])
            for g in set(DEFAULT_GROUPS) | set(extra)}
_COMPILED = {}


def _patterns(groups):
    """Компиляция с памятью: verify зовёт это на каждое число.

    Ключ — сами выражения, а не `id(groups)`. `id()` в CPython переиспользуется
    после сборки мусора: временный словарь групп получил бы адрес другого,
    уже собранного, и проверка группы пошла бы по чужим маркерам — молча, с
    правдоподобным результатом. Сейчас так вызывают только с модульным
    `DEFAULT_GROUPS`, у которого адрес постоянен, но опасность здесь не в том,
    что случается, а в том, что случится при первом же вызове с другим набором —
    ровно тот класс подмены, который продукт ищет у чужих работ.
    """
    key = tuple(sorted((g, tuple(al)) for g, al in groups.items()))
    if key not in _COMPILED:
        _COMPILED[key] = {g: [re.compile(a) for a in al] for g, al in groups.items()}
    return _COMPILED[key]


# Слова, которые не несут смысла метки. Список короткий и намеренно не
# «оптимизированный»: без него доля совпадения набивается служебными словами —
# `the`, `and`, `for` проходили прежний фильтр наравне с `Charlson`.
STOPWORDS = {
    "the", "and", "for", "with", "from", "that", "this", "was", "were", "are",
    "not", "but", "all", "any", "its", "their", "there", "which", "who", "whom",
    "into", "than", "then", "over", "under", "between", "among", "per", "each",
    "both", "such", "may", "can", "has", "had", "have", "been", "being", "its",
    "after", "before", "during", "within", "without", "about", "also", "more",
    "most", "less", "least", "some", "other", "others", "used", "using", "use",
}


def label_words(label: str) -> list:
    """Значимые слова метки: длиннее двух букв и не служебные."""
    return [w for w in re.findall(r"\w+", (label or "").lower())
            if len(w) > 2 and w not in STOPWORDS]


def word_counts(source: str) -> "collections.Counter":
    """Частоты слов документа. Считаются один раз на разбор."""
    return collections.Counter(re.findall(r"\w+", source.lower()))


# Ширина окна вокруг числа — она же вероятностная мера «слово попалось случайно».
WINDOW = CONTEXT_BEFORE + CONTEXT_AFTER


def word_weight(word: str, counts, source_len: int) -> float:
    """Сколько значит совпадение этого слова: 1 - вероятность попасть случайно.

    Стоп-лист общих слов проблему не решает: замер показал, что метку
    подтверждали `risk` и `group` — слова предметные, но встречающиеся в статье
    сотни раз, так что рядом с любым числом они стоят почти наверняка. Значимость
    слова определяется не списком, а документом: если слово встречается n раз в
    тексте длиной L, вероятность застать его в окне шириной W около n·W/L.
    `Charlson` при пяти вхождениях в 300 000 знаков весит почти 1, `group` при
    двухстах — почти 0. Список остаётся только для служебных слов языка.
    """
    if not source_len:
        return 1.0
    n = counts.get(word, 0)
    if n <= 0:
        return 1.0
    # Вероятность, что хотя бы одно из n вхождений попадёт в окно шириной W:
    # 1 - (1 - W/L)^n. Прямое произведение n·W/L, стоявшее здесь сначала, — его
    # линейное приближение, годное только при W << L. На коротком источнике оно
    # даёт больше единицы и обнуляет вес у всех слов сразу, включая осмысленные:
    # на синтетическом тексте в полторы тысячи знаков измерять становилось нечего.
    q = 1.0 - min(1.0, WINDOW / source_len)
    return max(0.0, q ** n)


def label_overlap(label: str, context: str, counts=None,
                  source_len: int = 0) -> float:
    """Доля значимых слов метки, стоящих рядом с числом. 0.0-1.0.

    Прежняя проверка была булевой и требовала **одного** совпавшего слова длиннее
    двух букв. Замер 29.08 показал, чего она стоит: выдуманные метки вроде «Mean
    age at the index date in the unexposed group» получали статус VERIFIED на
    числе, к которому не имели отношения, а медианная доля реально совпавших слов
    у подтверждённых чисел равнялась 0.23 (F-63). Доля возвращается наружу и
    попадает в отчёт: «сверено» — это утверждение о силе совпадения, и сила должна
    быть видна, а не спрятана в булевом флаге.
    """
    words = label_words(label)
    if not words or not context:
        return 0.0
    ctx = context.lower()
    if counts is None:
        # Без частот документа — равные веса; так зовут пробы и тесты.
        return sum(1 for w in words if w in ctx) / len(words)
    if source_len and WINDOW >= source_len * MAX_WINDOW_SHARE:
        # Окно вокруг числа покрывает заметную часть документа: «рядом с числом»
        # здесь означает «где-то в тексте», и совпадение слов не сообщает ничего.
        # Так бывает на коротком входе `{"text": ...}`. Честный ответ — «мерить
        # нечем», а не ноль: ноль был бы обвинением без оснований.
        return None
    weights = {w: word_weight(w, counts, source_len) for w in set(words)}
    total_w = sum(weights.values())
    if total_w < MIN_INFORMATIVE_WEIGHT:
        # Ни одно слово метки не различает мест документа. Так бывает в двух
        # случаях: метка целиком из слов, которые в статье повсюду, — и документ
        # короче окна вокруг числа, когда «рядом» означает «где угодно». В обоих
        # мера бессмысленна, и правильный ответ — «не берусь судить», а не ноль.
        # Ноль здесь означал бы обвинение в потере метки, которого нет оснований
        # выдвигать (поймано на коротком синтетическом источнике 29.08).
        return None
    return sum(weights[w] for w in set(words) if w in ctx) / total_w


# Порог подтверждения метки — 0.5, и это не граница между «верно» и «неверно».
#
# Замер 29.08 на разборе `10.1136/bmj-2023-076990` (440 чисел; контроль — та же
# метка, приставленная к чужому числу того же отчёта):
#
#   порог   свои проходят   чужие проходят
#   0.3         72%              24%
#   0.4         37%              11%
#   0.5         26%               8%
#   0.7         12%               3%
#
# Медиана у своих 0.36, у чужих 0.12. Распределения **перекрываются**, отношение
# держится около 3× на всех порогах, и точки, где одно кончается и начинается
# другое, не существует. Причина видна из самих данных: метка — это описание,
# сформулированное моделью, а не строка из статьи, и требовать дословного
# совпадения половины её слов с текстом вокруг числа неправомерно.
#
# Отсюда вывод, который важнее самого порога: **совпадение слов не является
# проверкой метки**, оно измеряет силу согласия и не выносит вердикта. Поэтому
# доля совпадения возвращается наружу числом, медиана попадает в сводку, а порог
# 0.5 выбран в сторону строгости и назван честно — при нём мимо проходит 8%
# заведомо чужих меток (F-63).
LABEL_THRESHOLD = 0.5

# Ниже этой суммы весов метка ничего не различает — см. `label_overlap`.
MIN_INFORMATIVE_WEIGHT = 0.05

# Доля документа, начиная с которой окно вокруг числа перестаёт что-либо выделять.
MAX_WINDOW_SHARE = 0.5


def check_label(label: str, context: str, threshold: float = LABEL_THRESHOLD,
                counts=None, source_len: int = 0) -> bool:
    """Стоит ли рядом с числом его метка.

    D-14 п.3: «19.7» само по себе ничего не значит, значение имеет
    «Charlson >=5, группа GLP-1, 19.7%». Сверяется пара, а не голое значение.
    """
    m = label_overlap(label, context, counts, source_len)
    return m is not None and m >= threshold


def check_group(claim: dict, context: str, matched: str, groups=None) -> str:
    """Направленная сверка: то ли это число, но у ТОЙ ЛИ группы.

    Защита от ошибки класса F-12 — инверсии направления. В проекте такая ошибка уже
    случалась: «контроль 9.2% против GLP-1 5.9%» было записано наоборот, и испорченный
    эталон снижал оценку модели за ВЕРНЫЙ ответ. Проверка наличия числа её не ловит:
    число-то в источнике есть, просто относится к другой группе.

    Возвращает: "ok" | "mismatch" | "unknown" (группа не заявлена или не распознана).
    """
    groups = groups or DEFAULT_GROUPS
    pats = _patterns(groups)
    want = (claim.get("group") or "").lower().strip()
    if not want:
        # группа не задана явно — пробуем вытащить из метки
        lab = (claim.get("label") or "").lower()
        hits = [g for g, al in pats.items() if any(a.search(lab) for a in al)]
        if len(hits) != 1:
            return "unknown"
        want = hits[0]
    if want not in groups:
        return "unknown"

    ctx = context.lower()
    pos = ctx.find(matched.lower())
    if pos < 0:
        return "unknown"

    # Ближайший к числу маркер группы решает, чьё это число. Обвинение в инверсии
    # выносится только тогда, когда чужой маркер действительно ближе: если маркеров
    # заявленной группы в контексте нет вовсе, это не доказательство обратного —
    # это отсутствие сведений.
    dist = {}
    for g, aliases in pats.items():
        for a in aliases:
            for m in a.finditer(ctx):
                d = abs(m.start() - pos)
                if d < dist.get(g, 10 ** 9):
                    dist[g] = d
    if not dist:
        return "unknown"
    nearest = min(dist, key=dist.get)
    if nearest == want:
        return "ok"
    if want not in dist:
        # Маркера заявленной группы рядом нет. Спорить не с чем — молчим.
        return "unknown"
    return "mismatch"


def verify(claims: list, source_text: str, groups: dict = None) -> dict:
    src = normalise(source_text)
    counts, src_len = word_counts(src), len(src)
    # Нулевое распределение документа — один проход, до всякой сверки.
    shapes = document_shapes(src)
    results, verified, unverified, unlabelled, inverted = [], 0, 0, 0, 0
    flipped = 0         # число есть, но с противоположным знаком
    unjudged = 0        # числа, у которых силу метки измерить нечем
    # Покрытие проверки группы. Без него «0 инверсий» читается как «проверили —
    # инверсий нет», а на деле означало «проверка отказалась отвечать»: на разборе
    # BMJ вердикт был вынесен для 0 чисел из 442, потому что маркеры групп заданы
    # под предметную область (F-63).
    group_seen = {"ok": 0, "mismatch": 0, "unknown": 0}
    for c in claims:
        num = str(c.get("value", "")).strip()
        label = c.get("label", "")
        if not num:
            continue
        occ, flip = find_occurrences_signed(num, src)
        bits = evidence_bits(num, shapes)
        grp = "unknown"
        if not occ and flip:
            # Значение в документе есть, но с противоположным знаком. Это не
            # «не найдено» и тем более не подтверждение: у разности рисков и у
            # стандартизованной разности знак и есть направление, и перепутать
            # его — та же ошибка класса F-12, что инверсия группы.
            best = max(flip, key=lambda o: (label_overlap(label, o["context"],
                                                          counts, src_len) or -1.0))
            flipped += 1
            results.append({**c, "status": "SIGN_MISMATCH", "group_check": grp,
                            "matched_as": best["as"], "context": best["context"],
                            "label_match": None, "occurrences": 0,
                            "evidence_bits": bits,
                            "chance": round(chance_rate(num, shapes), 4),
                            "note": ("the value appears in the paper with the opposite "
                                     "sign; for a risk difference the sign is the "
                                     "direction, so this is not a match")})
            continue
        if not occ:
            status = "UNVERIFIED"      # D-14 п.2: в расчёты не идёт
            unverified += 1
            results.append({**c, "status": status, "group_check": grp,
                            "matched_as": None, "context": None,
                            "label_match": 0.0, "occurrences": 0,
                            "evidence_bits": 0.0})
            continue

        # Из всех вхождений числа берётся то, рядом с которым метка совпадает
        # сильнее всего. Проверять первое попавшееся неверно: число живёт в статье
        # в среднем в двух местах, и «не та» позиция давала и ложные обвинения в
        # потере метки, и невозможность увидеть настоящую инверсию (F-63).
        best = max(occ, key=lambda o: (label_overlap(label, o["context"],
                                                     counts, src_len) or -1.0))
        match = label_overlap(label, best["context"], counts, src_len)
        grp = check_group(c, best["context"], best["as"], groups)
        if grp == "mismatch":
            status = "GROUP_MISMATCH"   # число есть, но у другой группы — инверсия
            inverted += 1
        elif match is None:
            # Мера неприменима — число найдено, о метке ничего не сказано.
            status = "VERIFIED"
            unjudged += 1
            verified += 1
        elif label and match < LABEL_THRESHOLD:
            status = "FOUND_LABEL_MISMATCH"
            unlabelled += 1
        else:
            status = "VERIFIED"
            verified += 1
        if grp in group_seen:
            group_seen[grp] += 1
        results.append({**c, "status": status, "group_check": grp,
                        "matched_as": best["as"], "context": best["context"],
                        "label_match": None if match is None else round(match, 3),
                        "occurrences": len(occ),
                        # Сколько стоит само нахождение этого числа в этом
                        # документе. Ноль означает «нашлось бы и без статьи».
                        "evidence_bits": bits,
                        "chance": round(chance_rate(num, shapes), 4)})
    matches = sorted(r["label_match"] for r in results
                     if r["status"] != "UNVERIFIED" and r.get("label_match") is not None)
    decided = group_seen["ok"] + group_seen["mismatch"]
    found_bits = sorted(r["evidence_bits"] for r in results
                        if r["status"] != "UNVERIFIED")
    strong = sum(1 for b in found_bits if b >= STRONG_BITS)
    return {
        "summary": {
            # `total` = сколько искали, и теперь это правда: пропускаемых заявок
            # больше нет, поэтому `found + unverified == total` сходится.
            "total": len(results),
            "found": len(results) - unverified,
            "unverified": unverified,
            # Из найденных — сколько несут вес улики. Ведущее число отчёта:
            # «найдено» без него говорит о размере документа, а не о статье.
            "strong": strong,
            "strong_bits_threshold": STRONG_BITS,
            "evidence_bits_total": round(sum(found_bits), 1),
            "evidence_bits_median": (found_bits[len(found_bits) // 2]
                                     if found_bits else None),
            "verified": verified,
            "group_mismatch": inverted,
            # Числа, найденные в статье с противоположным знаком. Стоят отдельной
            # строкой, а не в `unverified`: «нет в статье» и «есть, но наоборот» —
            # разные сведения, и второе тревожнее.
            "sign_mismatch": flipped,
            "found_but_label_mismatch": unlabelled,
            # Сила совпадения метки, а не только её факт.
            "label_match_median": (round(matches[len(matches) // 2], 3)
                                   if matches else None),
            "label_threshold": LABEL_THRESHOLD,
            # Числа, для которых силу метки измерить нечем: документ короче окна
            # или метка состоит из слов, встречающихся в нём повсюду.
            "label_not_judged": unjudged,
            # Сколько чисел проверка группы реально рассудила. Это число обязано
            # стоять рядом с `group_mismatch`, иначе ноль инверсий выглядит как
            # результат проверки, а не как её отказ.
            "group_checked": decided,
            "group_undecided": group_seen["unknown"],
        },
        "claims": results,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--claims", required=True,
                    help='JSON: [{"value":"19.7","label":"Charlson GLP-1"}, ...]')
    ap.add_argument("--source", required=True, help="файл первоисточника (xml/txt/md)")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    claims = json.load(open(a.claims))
    source = open(a.source, encoding="utf-8", errors="replace").read()
    res = verify(claims, source)

    if a.json:
        json.dump(res, sys.stdout, ensure_ascii=False, indent=2)
        return
    s = res["summary"]
    print(f"искали: {s['total']} · найдено: {s['found']} "
          f"(из них с весом улики: {s['strong']}) · подтверждено меткой: {s['verified']} · "
          f"НЕ НАЙДЕНО: {s['unverified']} · ИНВЕРСИЯ ГРУППЫ: {s['group_mismatch']} · "
          f"метка не совпала: {s['found_but_label_mismatch']}\n")
    for c in res["claims"]:
        mark = {"VERIFIED": "✅", "UNVERIFIED": "❌", "GROUP_MISMATCH": "🔄",
                "FOUND_LABEL_MISMATCH": "⚠️ "}.get(c["status"], "·")
        print(f"{mark} {str(c.get('value')):>10}  {c.get('label','')[:40]:<42} {c['status']}")
        if c["status"] in ("FOUND_LABEL_MISMATCH", "GROUP_MISMATCH"):
            print(f"     контекст: …{(c['context'] or '')[:110]}…")
    if s["unverified"]:
        print(f"\n⚠️  {s['unverified']} чисел не найдено в первоисточнике — "
              f"в отчёт и расчёты они не идут (D-14).")
    if s["group_mismatch"]:
        print(f"🔄 {s['group_mismatch']} чисел относятся к ДРУГОЙ группе — "
              f"инверсия направления, ошибка класса F-12.")


