"""
Сверка числа с ЯЧЕЙКОЙ таблицы, а не с окном текста вокруг него.

Зачем. До сих пор метка числа проверялась совпадением слов в окне 380 знаков:
модель написала «Charlson 5+ in the GLP-1 group», рядом с числом в плоском тексте
искались те же слова. Замер F-63 показал, чего это стоит — своё от подложного
такая мера отделяет втрое, распределения перекрываются, точки разделения нет. Так
и должно быть: метка — формулировка модели, а не строка из статьи.

Но у части чисел есть место, а не окрестность. Число из таблицы стоит в ячейке, у
ячейки есть подпись строки и заголовок колонки, и это **не описание, а адрес**.
Сверить адрес — решение, а не шкала.

Отсюда три исхода вместо двух:

  `cell`   — число найдено в конкретной ячейке, подпись строки и заголовок колонки
             согласуются с меткой модели. Сильнейшее из доступных подтверждений.
  `text`   — число есть в документе, но ячейки под него не нашлось: оно из прозы,
             из приложения, разобранного как текст, или таблица не разобралась.
             Здесь работает прежняя мера — вес улики и совпадение слов.
  `absent` — числа в документе нет.

## Проверка групп по колонкам: измерена и отклонена

Замысел был такой: заголовок колонки и есть название руки исследования, значит
проверка инверсий перестаёт зависеть от маркеров, вшитых под первую статью
проекта и покрывавших 4 числа из 474 на живом разборе. Реализовано и замерено.

**Результат отрицательный, и он записан здесь, а не выброшен.** На разборе
`10.1136/jitc-2025-014726` первая версия дала 59 «инверсий»; после двух
ограничений (метка относится к одному числу; в заявленной колонке стоит другое
число) — 6. Просмотрены все шесть: **ложных 6 из 6.**

  «95» из строки «E-value (lower 95% CI bound)» — слово value метки совпало с
      колонкой «Value»;
  «0.001» (P-значение) — слово risk из «at-risk surveillance» совпало с колонкой
      «Risk Ratio»;
  «1986» из колонки «Vaccinated», где оно и стоит, — слово risk из метки
      «2×2 table used for the absolute risk» совпало с колонкой «Risk Ratio».

Причина общая: заголовки таблиц полны служебных слов (Value, Risk, Ratio, P
value), а метки модели — прозы с теми же словами по другому поводу. Порогом это
не отсекается: точки, где ложные кончаются и настоящие начинаются, в данных нет —
та же картина, что у совпадения слов метки в F-63.

Поэтому `column_conflict` **не переводит число в GROUP_MISMATCH** и в вердикте не
участвует. Функция оставлена вызываемой и покрыта тестом (на синтетической
таблице ловит инверсию в обе стороны), но включать её в отчёт без измеренной
точности значило бы выдвигать обвинение на основании, которого нет. Проект уже
платил за это дважды — F-51 и F-56, — и правило «заводится только под измерение»
действует и тогда, когда измерение отвечает «нет».

## Обратная мера согласия адреса: тоже измерена и тоже отклонена

Второй заход. Раз заголовок короткий, а метка длинная, может быть, проверять
адрес надо в обратную сторону — «сколько слов подписи строки стоит в метке»?
Замер на том же разборе: подтверждённых адресов становится 272 вместо 32. Выборка
объясняет рост: подпись «Mortality» покрывается любым предложением со словом
mortality, «36 months» — любым, где есть «36-month». Адрес перестаёт указывать на
ячейку. Число выросло, знание — нет.

Оставлена строгая мера. 32 из 566 — мало, и это честная цифра: у остальных меткой
служит предложение на два десятка слов, цитирующее сразу восемь чисел, и сказать,
из какой ячейки взято каждое, по нему нельзя **никакой** мерой. Отсюда следующий
шаг, если он будет: по-числовые метки на стороне `verify_findings`, а не более
гибкая мера здесь.

Разбор таблиц для этого уже написан и до сих пор не использовался: `jats_tables`,
`docx_tables` и `pdf_tables` дают одинаковую форму, а `jats_tables.to_claims`
лежал импортированным в `pipeline` и не вызывался ни разу.
"""
import re

from .verify_numbers import label_overlap, label_words

# Тот же паттерн числа, что в остальных слоях: с разделителями разрядов.
NUM = re.compile(r"\d{1,3}(?:[  ,]\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?|\.\d+")

# Насколько метка модели должна совпасть с адресом ячейки, чтобы считать адрес
# подтверждённым. Порог тот же, что у прежней проверки метки (0.5), и намеренно:
# менять сразу и меру, и порог значит потерять возможность сравнить.
CELL_THRESHOLD = 0.5


def _norm(raw: str) -> str:
    return str(raw).replace(",", "").replace(" ", "").replace(" ", "")


def _shape(t: dict):
    """Заголовки и строки таблицы, откуда бы она ни пришла.

    JATS и PDF дают `columns` отдельно, .docx — нет: там заголовок это первая
    строка. Оркестратор различать источники не должен, поэтому различие снимается
    здесь.
    """
    cols = list(t.get("columns") or [])
    rows = [r for r in (t.get("rows") or []) if any(str(c).strip() for c in r)]
    if not cols and rows:
        cols, rows = [str(c) for c in rows[0]], rows[1:]
    name = t.get("label") or (t.get("caption") or "")[:70] or "table"
    return name, cols, rows


def build_index(tables: list) -> dict:
    """Значение -> список ячеек, в которых оно стоит.

    Ячейка описывается адресом: таблица, подпись строки, заголовок колонки. Плюс
    все заголовки таблицы — они нужны, чтобы поймать взятие числа из чужой
    колонки.
    """
    idx = {}
    for t in tables or []:
        name, cols, rows = _shape(t)
        for row in rows:
            cells = [str(c) for c in row]
            row_label = next((c for c in cells if c.strip() and not NUM.fullmatch(c.strip())),
                             cells[0] if cells else "")
            for i, cell in enumerate(cells):
                col = cols[i] if i < len(cols) else f"col{i}"
                for raw in NUM.findall(cell):
                    idx.setdefault(_norm(raw), []).append({
                        "table": name, "row": row_label, "column": col,
                        "columns": cols, "index": i, "row_cells": cells,
                    })
    return idx


def _address(cell: dict) -> str:
    return " ".join(x for x in (cell.get("row"), cell.get("column"),
                                cell.get("table")) if x)


def locate(value: str, label: str, idx: dict, counts=None, source_len: int = 0) -> dict | None:
    """Ячейка, чей адрес лучше всего согласуется с меткой модели.

    Возвращает `None`, если числа нет ни в одной разобранной таблице. Возвращает
    ячейку с `agreement` ниже порога, если число в таблицах есть, а адрес не
    сошёлся: это тоже сведение — «стоит в таблице, но не там, где сказано».
    """
    cells = idx.get(_norm(value))
    if not cells:
        return None
    best, best_score = None, -1.0
    for c in cells:
        score = label_overlap(label, _address(c), counts, source_len)
        score = -1.0 if score is None else score
        if score > best_score:
            best, best_score = c, score
    return {**best, "agreement": None if best_score < 0 else round(best_score, 3)}


def _covered(header: str, label: str) -> float:
    """Доля значимых слов ЗАГОЛОВКА, стоящих в метке модели.

    Направление важно и выбрано не наугад. Заголовок колонки короткий и точный
    («GLP-1», «Control»), метка модели длинная и описательная («Charlson 5+ in the
    GLP-1 group»). Доля слов метки в заголовке всегда мала — «GLP-1» покрывает
    треть метки и при полном согласии. Доля слов заголовка в метке ведёт себя
    правильно: «GLP-1» покрыт целиком, «Control» не покрыт вовсе.
    """
    hw = label_words(header)
    if not hw:
        return 0.0
    low = (label or "").lower()
    return sum(1 for w in hw if w in low) / len(hw)


# Метка, годная для суждения о колонке, должна относиться к ОДНОМУ числу.
# Замер 29.08 на живом разборе: без этого ограничения проверка вынесла 59
# «инверсий», и все просмотренные оказались ложными по одной причине — меткой
# служило целое предложение вида «Vaccinated patients had lower 36-month mortality
# (1453 vs ...)», которое называет одну руку и цитирует числа обеих. Предложение
# не может отвечать за то, из какой колонки взято каждое его число.
MAX_LABEL_WORDS = 12


def column_conflict(label: str, cell: dict):
    """Не из чужой ли колонки взято число.

    Проверка групп без вшитых маркеров: заголовки колонок этой самой таблицы и
    есть названия рук исследования. Прежняя проверка стояла на выражениях,
    вписанных под первую статью проекта, и на живом разборе выносила вердикт для
    4 чисел из 474 — «ноль инверсий» означало «проверка отказалась отвечать».

    Три условия, и все три обязательны. Каждое снято с ложных срабатываний, а не
    придумано заранее:

    1. **Метка относится к одному числу**, а не к предложению с несколькими.
    2. **Метка называет чужую колонку и не называет свою** — иначе это не
       путаница, а просто упоминание обеих рук.
    3. **В заявленной колонке той же строки стоит ДРУГОЕ число.** Инверсия — это
       «сказано про руку A, а взято значение руки B, тогда как у A значение своё».
       Если в заявленной колонке числа нет или оно то же самое, инвертировать
       нечего, и обвинять не в чем.

    Молчание при сомнении обязательно: ложная инверсия — ошибка того же класса
    F-12, ради которой проверка и заводилась, и проект уже платил за неё дважды
    (F-51, F-56).
    """
    cols = [str(c) for c in (cell.get("columns") or [])]
    words = label_words(label)
    if len(cols) < 2 or not words or len(words) > MAX_LABEL_WORDS:
        return None
    own = cols[cell["index"]] if cell["index"] < len(cols) else ""
    if _covered(own, label) > 0:
        return None
    rival, rival_at, rival_score = None, None, 0.0
    for j, c in enumerate(cols):
        if j == cell["index"] or not c.strip():
            continue
        sc = _covered(c, label)
        if sc > rival_score:
            rival, rival_at, rival_score = c, j, sc
    if not rival or rival_score < CELL_THRESHOLD:
        return None
    row_cells = cell.get("row_cells") or []
    claimed = str(row_cells[rival_at]) if rival_at < len(row_cells) else ""
    claimed_nums = {_norm(x) for x in NUM.findall(claimed)}
    mine = {_norm(x) for x in NUM.findall(
        str(row_cells[cell["index"]]) if cell["index"] < len(row_cells) else "")}
    if not claimed_nums or claimed_nums == mine:
        return None
    return {"claimed_column": rival, "actual_column": own or f"col{cell['index']}",
            "value_in_claimed_column": claimed.strip()[:40],
            "table": cell.get("table"), "row": cell.get("row"),
            "note": "the label names another column of the same table, and that column "
                    "holds a different value for this row — so the number belongs to a "
                    "different arm than the one claimed"}
